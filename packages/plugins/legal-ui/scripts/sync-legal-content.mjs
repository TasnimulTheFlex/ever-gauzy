#!/usr/bin/env node
// Base360 publishes its policies on its own site; never vendor another operator's contracts.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const documents = [
	['tos', 'Terms of Service', 'https://base360.ai/legal'],
	['privacy', 'Privacy Policy', 'https://base360.ai/legal#privacy'],
	['cookies', 'Cookie Policy', 'https://base360.ai/legal']
];

for (const [document, title, url] of documents) {
	const html = `<p>Base360 publishes its current ${title.toLowerCase()} on its website.</p><p><a href="${url}" target="_blank" rel="noopener noreferrer">Read the Base360 ${title}</a>.</p><p>Contact <a href="mailto:support@base360.ai">support@base360.ai</a> for policy questions.</p>`;
	assert.match(url, /^https:\/\/base360\.ai\/legal(?:#privacy)?$/);
	assert.doesNotMatch(html, /gauzy|\bever\b/i);
	const content = {
		document,
		product: 'gauzy',
		productName: 'Base360 Time Tracker',
		domain: 'base360.ai',
		entity: 'Base360',
		entityId: 'base360',
		locale: 'en',
		version: '',
		effectiveDate: '',
		sha256: createHash('sha256').update(html).digest('hex'),
		title,
		html
	};
	writeFileSync(new URL(`../src/lib/content/${document}.en.generated.ts`, import.meta.url),
		`// Generated by scripts/sync-legal-content.mjs.\nimport { ILegalDocument } from '../models/legal-document.model';\n\nexport const LEGAL_${document.toUpperCase()}_EN: ILegalDocument = ${JSON.stringify(content, null, '\t')};\n`);
}
